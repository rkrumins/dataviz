#!/usr/bin/env node
/**
 * Generate per-page documentation metadata (last-updated date + source path)
 * from git, so the docs and guide can show a freshness signal and an
 * "Edit on GitHub" link without a backend. Runs before build (prebuild) and
 * is resilient: if git history is unavailable, dates come back empty rather
 * than failing the build.
 *
 * Output: src/components/docs/reading/docMeta.generated.ts
 */
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const FRONTEND = resolve(here, '..')
const REPO = resolve(FRONTEND, '..')

/** Pull { slug -> repoRelativePath } out of a config file's entry list. */
function parseEntries(configPath) {
  const src = readFileSync(configPath, 'utf8')
  const re = /slug:\s*'([^']+)'[\s\S]{0,500}?import\('@(docs|root)\/([^?']+\.md)/g
  const out = {}
  let m
  while ((m = re.exec(src))) {
    const [, slug, alias, rel] = m
    out[slug] = alias === 'docs' ? `docs/${rel}` : rel
  }
  return out
}

function lastUpdated(repoRelPath) {
  try {
    const d = execSync(`git log -1 --format=%cs -- "${repoRelPath}"`, {
      cwd: REPO,
      stdio: ['ignore', 'pipe', 'ignore'],
    })
      .toString()
      .trim()
    return d || ''
  } catch {
    return ''
  }
}

function build(map) {
  const result = {}
  for (const [slug, path] of Object.entries(map)) {
    result[slug] = { updated: lastUpdated(path), path }
  }
  return result
}

const docs = build(parseEntries(resolve(FRONTEND, 'src/components/docs/docsConfig.ts')))
const guide = build(parseEntries(resolve(FRONTEND, 'src/components/guide/guideConfig.ts')))

const banner = `// AUTO-GENERATED by scripts/gen-doc-meta.mjs — do not edit by hand.\n// Last-updated dates and source paths come from git at build time.\n`
const body =
  banner +
  `export interface DocMeta { updated: string; path: string }\n` +
  `export const GITHUB_REPO = 'rkrumins/dataviz'\n` +
  `export const docMeta: Record<string, DocMeta> = ${JSON.stringify(docs, null, 2)}\n` +
  `export const guideMeta: Record<string, DocMeta> = ${JSON.stringify(guide, null, 2)}\n`

const outPath = resolve(FRONTEND, 'src/components/docs/reading/docMeta.generated.ts')
writeFileSync(outPath, body)
console.log(
  `[gen-doc-meta] wrote ${Object.keys(docs).length} docs + ${Object.keys(guide).length} guide entries`,
)
